import { test, expect } from '@playwright/test';

test('Login, create category and product, search, edit, deactivate, logout', async ({ page }) => {
  const failures = [];
  page.on('pageerror', (error) => { failures.push(error.message); console.error('Browser script error:', error.message); });
  page.on('requestfailed', (request) => console.error('Browser request failed:', new URL(request.url()).pathname, request.failure()?.errorText));
  await page.goto('/login');
  await page.screenshot({ path: 'test-results/login-desktop.png', fullPage: true });
  await page.getByLabel(/Tên đăng nhập/).fill(process.env.E2E_USERNAME, { timeout: 10_000 });
  await page.getByLabel(/Mật khẩu/).fill(process.env.E2E_PASSWORD);
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click();
  await expect(page).toHaveURL(/\/products$/);
  await expect(page.getByRole('heading', { name: 'Sản phẩm', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Danh mục', exact: true }).click();
  await page.getByRole('button', { name: 'Thêm danh mục', exact: true }).first().click();
  const category = 'Browser QA ' + Date.now();
  const categoryDialog = page.getByRole('dialog');
  await categoryDialog.getByLabel(/Tên danh mục/).fill(category);
  await categoryDialog.getByLabel('Mô tả', { exact: true }).fill('Created through the real React form');
  await categoryDialog.getByRole('button', { name: 'Lưu danh mục', exact: true }).click();
  await expect(categoryDialog).toBeHidden();
  await page.getByPlaceholder('Tìm danh mục…').fill(category);
  await expect(page.getByRole('cell', { name: category, exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Sản phẩm', exact: true }).click();
  await page.getByRole('button', { name: 'Thêm sản phẩm', exact: true }).first().click();
  const productDialog = page.getByRole('dialog');
  const sku = 'BROWSER-' + Date.now();
  await productDialog.getByLabel(/SKU sản phẩm/).fill(sku);
  await productDialog.getByLabel(/Tên sản phẩm/).fill('Browser Verified Product');
  await productDialog.getByLabel(/Danh mục/).click();
  await page.getByRole('option', { name: category, exact: true }).click();
  await productDialog.getByLabel(/Giá bán/).fill('250000');
  await productDialog.getByRole('button', { name: 'Lưu sản phẩm', exact: true }).click();
  await expect(productDialog).toBeHidden();
  await page.getByPlaceholder('Tìm tên hoặc mã SKU…').fill(sku);
  await expect(page.getByRole('cell', { name: sku, exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Browser Verified Product', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Tồn kho', exact: true }).click();
  await page.getByLabel('Tìm sản phẩm hoặc SKU').fill(sku);
  const stockRow = page.getByRole('row').filter({ hasText: sku });
  await expect(stockRow).toBeVisible();
  await stockRow.getByRole('button', { name: 'Nhập', exact: true }).click();
  const receiptDialog = page.getByRole('dialog');
  await receiptDialog.getByLabel('Số lượng').fill('10');
  await receiptDialog.getByLabel('Lý do').fill('Browser smoke receipt');
  await receiptDialog.getByRole('button', { name: 'Xác nhận thao tác', exact: true }).click();
  await expect(receiptDialog).toBeHidden();
  await expect(stockRow.getByText('10', { exact: true })).toBeVisible();
  await stockRow.getByRole('button', { name: 'Xuất', exact: true }).click();
  const issueDialog = page.getByRole('dialog');
  await issueDialog.getByLabel('Số lượng').fill('2');
  await issueDialog.getByLabel('Lý do').fill('Browser smoke issue');
  await issueDialog.getByRole('button', { name: 'Xác nhận thao tác', exact: true }).click();
  await expect(issueDialog).toBeHidden();
  await expect(stockRow.getByText('8', { exact: true })).toBeVisible();
  await page.getByRole('navigation').getByRole('link', { name: 'Lịch sử biến động', exact: true }).click();
  await expect(page.getByRole('cell', { name: sku, exact: false }).first()).toBeVisible();
  await expect(page.getByText('Browser smoke receipt', { exact: true })).toBeVisible();
  await expect(page.getByText('Browser smoke issue', { exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/stock-movements-desktop.png', fullPage: true });
  await page.getByRole('link', { name: 'Sản phẩm', exact: true }).click();
  await page.getByPlaceholder('Tìm tên hoặc mã SKU…').fill(sku);
  await expect(page.getByRole('cell', { name: sku, exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/products-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Sửa Browser Verified Product', exact: true }).click();
  await productDialog.getByLabel(/Tên sản phẩm/).fill('Browser Updated Product');
  await productDialog.getByRole('button', { name: 'Lưu sản phẩm', exact: true }).click();
  await expect(productDialog).toBeHidden();
  await expect(page.getByText('Browser Updated Product', { exact: true }).first()).toBeVisible();
  await page.getByRole('button', { name: 'Ngừng hoạt động Browser Updated Product', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Ngừng hoạt động', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeHidden();
  await expect(page.getByRole('cell', { name: sku, exact: true })).toHaveCount(0);
  await page.goto('/mcp/lab');
  await page.getByRole('button', { name: 'ListTools', exact: true }).click();
  await expect(page.getByRole('cell', { name: 'GetInventorySummary', exact: true })).toBeVisible();
  await page.goto('/mcp/playground?tool=GetInventorySummary');
  await page.getByLabel('Arguments · JSON object', { exact: true }).fill('{}');
  await page.getByRole('button', { name: 'Run Tool', exact: true }).click();
  await expect(page.getByText('Thực thi thành công', { exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/mcp-playground-desktop.png', fullPage: true });
  await page.goto('/mcp/trace');
  await page.getByRole('button', { name: /Xem execution / }).first().click();
  await expect(page.getByText('MCP RESULT · JSON', { exact: true })).toBeVisible();
  await page.goto('/ai');
  await expect(page.getByRole('button', { name: 'Gửi', exact: true })).toBeDisabled();
  await page.screenshot({ path: 'test-results/ai-unconfigured-desktop.png', fullPage: true });
  await page.goto('/categories');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Mở menu', exact: true }).click();
  await page.getByRole('link', { name: 'Danh mục', exact: true }).last().click();
  await expect(page.getByRole('heading', { name: 'Danh mục sản phẩm' })).toBeVisible();
  await page.screenshot({ path: 'test-results/categories-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Đăng xuất', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Đăng xuất', exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  expect(failures).toEqual([]);
});
